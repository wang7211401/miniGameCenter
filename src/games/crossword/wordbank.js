// 解析 + 清洗：过滤长度<2 或字段缺失的条目，按答案去重
export const WORDS = (() => {
  const seen = new Set();
  const out = [];
  for (const line of RAW) {
    const [w, h, s, r] = line.split('|');
    if (!w || w.length < 2 || !h || !s || !r) continue;
    if (seen.has(w)) continue;
    seen.add(w);
    out.push({ w, h, s, r });
  }
  return out;
})();

// 按长度分组索引，供生成器快速取词
export const BY_LEN = {};
for (const word of WORDS) {
  const n = word.w.length;
  if (!BY_LEN[n]) BY_LEN[n] = [];
  BY_LEN[n].push(word);
}

export function wordsOfLength(n) {
  return BY_LEN[n] || [];
}

export function findWord(w) {
  return WORDS.find(x => x.w === w);
}
